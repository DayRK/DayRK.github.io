-- Portfolio schema for Supabase (Postgres).
-- Paste this into the Supabase SQL editor and run it once.

create table if not exists public.projects (
  id bigint generated by default as identity primary key,
  title text not null,
  summary text not null,
  stack jsonb not null default '[]'::jsonb,
  link text not null,
  show_preview boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Adds the column to a table created before it existed.
alter table public.projects
  add column if not exists show_preview boolean not null default true;

create table if not exists public.experience (
  id bigint generated by default as identity primary key,
  role text not null,
  company text not null,
  period text not null,
  description text not null,
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.certificates (
  id bigint generated by default as identity primary key,
  title text not null,
  issuer text not null,
  issued_at text not null,
  link text not null default '',
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.posts (
  id bigint generated by default as identity primary key,
  slug text not null,
  title text not null,
  excerpt text not null,
  content text not null,
  kind text not null default 'blog',
  tags jsonb not null default '[]'::jsonb,
  published boolean not null default false,
  published_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint posts_slug_key unique (slug),
  constraint posts_kind_check check (kind in ('blog', 'research'))
);

create index if not exists experience_sort_order_idx on public.experience (sort_order);
create index if not exists certificates_sort_order_idx on public.certificates (sort_order);
create index if not exists posts_created_at_idx on public.posts (created_at desc);
create index if not exists posts_published_idx on public.posts (published);

create table if not exists public.availability (
  id bigint primary key default 1,
  status text not null default 'Open to Commissions',
  updated_at timestamptz not null default now()
);

insert into public.availability (id, status)
values (1, 'Open to Commissions')
on conflict (id) do nothing;

-- Phase 15: per-module public visibility ----------------------------------
-- One row per module. A module with no row (or visible = true) is shown.
create table if not exists public.module_visibility (
  module text primary key,
  visible boolean not null default true,
  updated_at timestamptz not null default now()
);

insert into public.module_visibility (module, visible)
values
  ('about', true),
  ('projects', true),
  ('experience', true),
  ('certificates', true),
  ('github', true),
  ('contact', true),
  ('blog', true),
  ('resume', true),
  ('search', true)
on conflict (module) do nothing;

create table if not exists public.audit_log (
  id bigint generated by default as identity primary key,
  action text not null,
  entity text not null,
  entity_id text,
  actor text not null default 'admin',
  detail text,
  created_at timestamptz not null default now()
);

create index if not exists audit_log_created_at_idx on public.audit_log (created_at desc);

alter table public.projects enable row level security;
alter table public.availability enable row level security;
alter table public.experience enable row level security;
alter table public.certificates enable row level security;
alter table public.posts enable row level security;
alter table public.audit_log enable row level security;
alter table public.module_visibility enable row level security;

-- Audit rows are write-only from the server and readable by nobody through the
-- anon key: no select policy is created, so the public cannot read them.

-- The visibility flags are read by the public site (so it knows what to hide)
-- but the anon key can never write them. Only the server-side API changes them.
drop policy if exists "Public can read module visibility" on public.module_visibility;
create policy "Public can read module visibility"
  on public.module_visibility
  for select
  using (true);

-- Postgres has no "create policy if not exists", so each policy is dropped
-- first. That keeps this file safe to run more than once.
drop policy if exists "Allow public read access to projects" on public.projects;
drop policy if exists "Public can read projects" on public.projects;
create policy "Public can read projects"
  on public.projects
  for select
  using (true);

drop policy if exists "Allow public read access to availability" on public.availability;
drop policy if exists "Public can read availability" on public.availability;
create policy "Public can read availability"
  on public.availability
  for select
  using (true);

drop policy if exists "Public can read experience" on public.experience;
create policy "Public can read experience"
  on public.experience
  for select
  using (true);

drop policy if exists "Public can read certificates" on public.certificates;
create policy "Public can read certificates"
  on public.certificates
  for select
  using (true);

-- Only published posts are readable with the anon key. Drafts stay private and
-- are only visible to the admin dashboard through the server-side API.
drop policy if exists "Public can read published posts" on public.posts;
create policy "Public can read published posts"
  on public.posts
  for select
  using (published = true);

-- module_visibility has a select policy above but no insert/update/delete
-- policy on purpose: only the service-role key can change it.

-- Writes are intentionally left without a policy.
-- The public site reads with the anon key above. All changes go through the
-- Next.js API routes, which use the service-role key on the server only.
-- That key bypasses row level security, so the browser can never write
-- directly to these tables.
drop policy if exists "Allow authenticated inserts on projects" on public.projects;
drop policy if exists "Allow authenticated updates on projects" on public.projects;
drop policy if exists "Allow authenticated deletes on projects" on public.projects;
drop policy if exists "Allow authenticated updates on availability" on public.availability;

-- Phase 8: media library ----------------------------------------------------
create table if not exists public.media (
  id bigint generated by default as identity primary key,
  path text not null,
  url text not null,
  filename text not null,
  mime_type text not null,
  size_bytes bigint not null default 0,
  alt text not null default '',
  created_at timestamptz not null default now(),
  constraint media_path_key unique (path)
);

create index if not exists media_created_at_idx on public.media (created_at desc);

-- Contact inbox -------------------------------------------------------------
create table if not exists public.contact_messages (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null,
  subject text not null default '',
  budget text not null default '',
  message text not null,
  is_read boolean not null default false,
  created_at timestamptz not null default now()
);

create index if not exists contact_messages_created_at_idx on public.contact_messages (created_at desc);

-- Added after the first release, so existing databases pick it up safely.
alter table public.contact_messages add column if not exists budget text not null default '';

alter table public.media enable row level security;
alter table public.contact_messages enable row level security;

-- No policies on purpose: media rows and contact messages are reachable only
-- through the server-side API with the service-role key. The bucket below is
-- public so uploaded images can be displayed, but nothing can be listed or
-- deleted without the server key.

insert into storage.buckets (id, name, public)
values ('media', 'media', true)
on conflict (id) do nothing;
