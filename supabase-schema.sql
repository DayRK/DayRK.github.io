create table if not exists public.projects (
  id bigint generated by default as identity primary key,
  title text not null,
  summary text not null,
  stack jsonb not null default '[]'::jsonb,
  link text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.availability (
  id bigint primary key default 1,
  status text not null default 'Open to Commissions',
  updated_at timestamptz not null default now()
);

insert into public.availability (id, status)
values (1, 'Open to Commissions')
on conflict (id) do nothing;

alter table public.projects enable row level security;
alter table public.availability enable row level security;

create policy if not exists "Allow public read access to projects"
  on public.projects
  for select
  using (true);

create policy if not exists "Allow public read access to availability"
  on public.availability
  for select
  using (true);

create policy if not exists "Allow authenticated inserts on projects"
  on public.projects
  for insert
  to authenticated
  with check (true);

create policy if not exists "Allow authenticated updates on projects"
  on public.projects
  for update
  to authenticated
  using (true)
  with check (true);

create policy if not exists "Allow authenticated deletes on projects"
  on public.projects
  for delete
  to authenticated
  using (true);

create policy if not exists "Allow authenticated updates on availability"
  on public.availability
  for update
  to authenticated
  using (true)
  with check (true);
